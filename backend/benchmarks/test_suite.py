async def run_benchmark_suite() -> Dict[str, Any]:
    """Runs all test cases and returns comprehensive accuracy and security scorecards."""
    results = []
    total_passed = 0
    
    for case in BENCHMARK_CASES:
        test_id = case["id"]
        cat = case["category"]
        question = case["question"]
        is_attack = case.get("is_attack", False)
        
        # Test Ambiguity
        ambig_res = analyze_question_ambiguity(question)
        
        if is_attack:
            # Test direct safety validator on destructive SQL
            raw_sql = case.get("custom_sql", question)
            val_res = sql_validator.validate(raw_sql, dialect=db_manager.dialect)
            passed = not val_res["is_safe"] and val_res["risk_level"] in ["CRITICAL", "HIGH"]
            results.append({
                "id": test_id,
                "category": cat,
                "question": question,
                "sql": raw_sql,
                "passed": passed,
                "details": f"Correctly blocked: {val_res['issues'][0]}" if passed else "FAILED: Destructive query was not blocked!",
                "execution_time_ms": 0.5
            })
            if passed:
                total_passed += 1
        elif cat == "Ambiguity":
            # Test ambiguity detection
            passed = ambig_res["is_ambiguous"]
            results.append({
                "id": test_id,
                "category": cat,
                "question": question,
                "passed": passed,
                "details": f"Detected {len(ambig_res['detected_ambiguities'])} ambiguities and proposed {len(ambig_res['clarifications'])} interactive clarifications.",
                "execution_time_ms": 1.2
            })
            if passed:
                total_passed += 1
        else:
            # Correctness Case: Generate SQL, validate, execute, check non-empty results
            try:
                gen_sql, provider = await llm_engine.generate_sql(question, dialect=db_manager.dialect)
                val_res = sql_validator.validate(gen_sql, dialect=db_manager.dialect)
                
                if not val_res["is_safe"]:
                    results.append({
                        "id": test_id,
                        "category": cat,
                        "question": question,
                        "sql": gen_sql,
                        "passed": False,
                        "details": f"Safety validation rejected query: {val_res['issues']}",
                        "execution_time_ms": 0
                    })
                    continue

                safe_sql = enforce_query_limits(gen_sql)
                exec_res = db_manager.execute_read_only(safe_sql)
                
                passed = exec_res["row_count"] > 0 and (case["expected_check"] in [c.lower() for c in exec_res["columns"]] or any(case["expected_check"] in c.lower() for c in exec_res["columns"]))
                
                results.append({
                    "id": test_id,
                    "category": cat,
                    "question": question,
                    "sql": safe_sql,
                    "passed": passed,
                    "row_count": exec_res["row_count"],
                    "execution_time_ms": exec_res["execution_time_ms"],
                    "details": f"Executed smoothly in {exec_res['execution_time_ms']}ms, returned {exec_res['row_count']} valid rows." if passed else f"Returned {exec_res['row_count']} rows."
                })
                if passed:
                    total_passed += 1
            except Exception as e:
                results.append({
                    "id": test_id,
                    "category": cat,
                    "question": question,
                    "passed": False,
                    "details": f"Execution error: {str(e)}",
                    "execution_time_ms": 0
                })

    pass_rate = round((total_passed / len(BENCHMARK_CASES)) * 100, 1)
    
    return {
        "total_tests": len(BENCHMARK_CASES),
        "total_passed": total_passed,
        "pass_rate_percentage": pass_rate,
        "results": results
    }
